CHS_TABLE = [{"od": od, "thk": thk, "wt": wt} for od, thk, wt, *_ in RAW_CHS]

def get_drum(swl_t, final_dia, lift_m, falls, reeving, duty):
    rope_dia_mm = final_dia
    rope_dia_cm = rope_dia_mm / 10.0
    d_req = rope_dia_mm * 20
    pitch_mm = rope_dia_mm + 2
    pitch_cm = pitch_mm / 10.0
    
    S_kg = (swl_t / falls) * 1000
    
    thk_calc_cm = S_kg / (pitch_cm * SIGMA_ALLOW)
    thk_calc_mm = thk_calc_cm * 10
    
    depth_groove_cm = 0.35 * rope_dia_cm
    depth_groove_mm = depth_groove_cm * 10
    
    thk_req_cm = thk_calc_cm + depth_groove_cm
    thk_req_mm = thk_req_cm * 10
    if thk_req_mm < 8:
        thk_req_mm = 8
        thk_req_cm = 0.8

    sorted_chs = sorted(CHS_TABLE, key=lambda x: (x["od"], x["thk"]))
    candidate_ods = sorted(set([c["od"] for c in sorted_chs if c["od"] >= d_req]))
    
    selected = None
    induced_stress = 0
    eff_thk_used = 0
    
    for od in candidate_ods:
        options = sorted([c for c in sorted_chs if c["od"] == od], key=lambda x: x["thk"])
        for chs in options:
            if chs["thk"] + 0.001 < thk_req_mm:
                continue
            # EFFECTIVE THICKNESS = chs thk - groove depth
            eff_thk_mm = chs["thk"] - depth_groove_mm - 3 # 3mm machining
            if eff_thk_mm <= 0:
                continue
            eff_thk_cm = eff_thk_mm / 10.0
            stress = S_kg / (pitch_cm * eff_thk_cm)
            if stress <= SIGMA_ALLOW:
                selected = chs
                induced_stress = stress
                eff_thk_used = eff_thk_mm
                break
        if selected:
            break
            
    if not selected:
        selected = sorted_chs[-1]
        eff_thk_mm = selected["thk"] - depth_groove_mm - 3
        eff_thk_cm = eff_thk_mm / 10.0 if eff_thk_mm > 0 else 0.1
        induced_stress = S_kg / (pitch_cm * eff_thk_cm)
        eff_thk_used = eff_thk_mm

    extra_turns = 3
    drum_od = selected["od"]
    pcd = drum_od - rope_dia_mm
    rope_per_side = lift_m * (falls / reeving)
    turns = (rope_per_side * 1000) / (3.1416 * pcd) if pcd > 0 else 0
    total_turns = math.ceil(turns + extra_turns)

    drum_length_mm = (2 * (total_turns * pitch_mm) + 400) if reeving == 2 else (total_turns * pitch_mm + 80)

    return {
        "drum_od": selected["od"],
        "drum_thk_mm": selected["thk"],
        "drum_thk_eff_mm": round(eff_thk_used, 2),
        "drum_length_mm": round(drum_length_mm,0),
        "drum_pcd": round(pcd,1),
        "pitch_mm": pitch_mm,
        "total_turns": int(total_turns),
        "turns": round(turns,2),
        "extra_turns": extra_turns,
        "induced_stress": round(induced_stress,2),
        "thk_req_mm": round(thk_req_mm,2),
        "thk_calc_mm": round(thk_calc_mm,2),
        "depth_groove_mm": round(depth_groove_mm,2),
        "d_req": round(d_req,1)
    }